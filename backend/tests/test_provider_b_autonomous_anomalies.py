@pytest.mark.asyncio
async def test_provider_b_autonomous_duplicate_event_deterministic(test_db):
    """
    F4 Requirement: Deterministic seeded autonomous duplicate event generation.
    EventProcessor intercepts duplicate via idempotency filter without duplicate agent allocation.
    """
    provider_b = get_telecom_provider("PROVIDER_B")
    provider_b.configure_anomalies(enabled=True, duplicate_probability=1.0, out_of_order_probability=0.0, seed=42)

    campaign = Campaign(name="Camp-Dup-Test", dialing_mode=DialingMode.PROGRESSIVE, status=CampaignStatus.RUNNING)
    test_db.add(campaign)
    await test_db.commit()
    await test_db.refresh(campaign)

    agent = Agent(name="Agent-Dup-Target", status=AgentStatus.DIALING)
    borrower = Borrower(campaign_id=campaign.id, name="Dup Borrower", phone_number="+15551212", status=BorrowerStatus.DIALING)
    test_db.add(agent)
    test_db.add(borrower)
    await test_db.commit()
    await test_db.refresh(agent)
    await test_db.refresh(borrower)

    call = Call(
        campaign_id=campaign.id,
        borrower_id=borrower.id,
        agent_id=agent.id,
        provider_id="PROVIDER_B",
        call_state=CallState.INITIATED,
        outcome=CallOutcome.PENDING
    )
    test_db.add(call)
    agent.current_call_id = call.id
    await test_db.commit()
    await test_db.refresh(call)

    # 1. Primary event: CONNECTED
    primary_evt_id = f"evt-prim-{uuid.uuid4().hex[:8]}"
    res_primary = await EventProcessor.process_provider_event(
        db=test_db,
        event_id=primary_evt_id,
        provider_id="PROVIDER_B",
        call_id=call.id,
        event_type=CallState.CONNECTED
    )
    assert res_primary["status"] == "PROCESSED"
    await test_db.refresh(agent)
    assert agent.status == AgentStatus.CONNECTED
    assert agent.total_calls == 1

    # 2. Autonomous duplicate event generated by Provider B
    anomalies = await provider_b.maybe_generate_autonomous_anomalies(
        db=test_db,
        call_id=call.id,
        primary_event_id=primary_evt_id,
        current_state=CallState.CONNECTED
    )

    assert len(anomalies) == 1
    assert anomalies[0]["anomaly_type"] == "AUTONOMOUS_DUPLICATE"
    dup_res = anomalies[0]["result"]
    assert dup_res["status"] == "DUPLICATE_IGNORED"
    assert dup_res["is_duplicate"] is True

    # Invariant: Agent total_calls must NOT double count
    await test_db.refresh(agent)
    assert agent.total_calls == 1

@pytest.mark.asyncio
async def test_provider_b_autonomous_out_of_order_event_deterministic(test_db):
    """
    F4 Requirement: Deterministic seeded autonomous out-of-order event generation.
    Monotonic state hierarchy prevents regression of completed call.
    """
    provider_b = get_telecom_provider("PROVIDER_B")
    provider_b.configure_anomalies(enabled=True, duplicate_probability=0.0, out_of_order_probability=1.0, seed=99)

    campaign = Campaign(name="Camp-OOO-Test", dialing_mode=DialingMode.PROGRESSIVE, status=CampaignStatus.RUNNING)
    test_db.add(campaign)
    await test_db.commit()
    await test_db.refresh(campaign)

    agent = Agent(name="Agent-OOO-Target", status=AgentStatus.AVAILABLE)
    borrower = Borrower(campaign_id=campaign.id, name="OOO Borrower", phone_number="+15553434", status=BorrowerStatus.COMPLETED)
    test_db.add(agent)
    test_db.add(borrower)
    await test_db.commit()
    await test_db.refresh(agent)
    await test_db.refresh(borrower)

    # Call is COMPLETED
    call = Call(
        campaign_id=campaign.id,
        borrower_id=borrower.id,
        agent_id=agent.id,
        provider_id="PROVIDER_B",
        call_state=CallState.COMPLETED,
        outcome=CallOutcome.SUCCESS
    )
    test_db.add(call)
    await test_db.commit()
    await test_db.refresh(call)

    # Autonomous out-of-order event emission (delayed ANSWERED arriving for COMPLETED call)
    anomalies = await provider_b.maybe_generate_autonomous_anomalies(
        db=test_db,
        call_id=call.id,
        primary_event_id=f"evt-comp-{uuid.uuid4().hex[:8]}",
        current_state=CallState.COMPLETED
    )

    assert len(anomalies) == 1
    assert anomalies[0]["anomaly_type"] == "AUTONOMOUS_OUT_OF_ORDER"
    ooo_res = anomalies[0]["result"]
    assert ooo_res["is_out_of_order"] is True
    assert ooo_res.get("state_applied", False) is False

    # Invariant: Call state remains strictly COMPLETED
    await test_db.refresh(call)
    assert call.call_state == CallState.COMPLETED

@pytest.mark.asyncio
async def test_provider_b_anomalies_cannot_bypass_safety_controller(test_db):
    """
    F4 Requirement: Ensure autonomous anomalies cannot bypass SafetyController or inflate capacity.
    """
    provider_b = get_telecom_provider("PROVIDER_B")
    provider_b.configure_anomalies(enabled=True, duplicate_probability=0.5, out_of_order_probability=0.5, seed=1)

    campaign = Campaign(name="Camp-Safety-Check", dialing_mode=DialingMode.PROGRESSIVE, status=CampaignStatus.RUNNING)
    test_db.add(campaign)
    await test_db.commit()
    await test_db.refresh(campaign)

    # 3 available agents
    for i in range(3):
        test_db.add(Agent(name=f"Safe-Agent-{i}", status=AgentStatus.AVAILABLE))
    await test_db.commit()

    # Safety decision evaluation targeting Provider B
    dec = await SafetyController.evaluate_dial_request(
        db=test_db,
        campaign_id=campaign.id,
        requested_calls=10,
        dialing_mode=DialingMode.PROGRESSIVE,
        provider_id="PROVIDER_B"
    )

    # SafetyController strictly clamps to safe capacity (3) despite Provider B anomaly configuration
    assert dec.decision == SafetyDecisionType.REDUCE
    assert dec.approved_calls == 3
    assert dec.rejected_calls == 7
